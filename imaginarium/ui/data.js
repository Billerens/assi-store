export function allPlaces(state) {
  return places.concat(
    state.objects.flatMap((o) =>
      o.shape.parts
        .map((p, i) => ({ p, i }))
        .filter(({ p }) => ['surface', 'shelf'].includes(p.action))
        .map(({ p, i }) => ({
          id: o.id + '-' + i,
          name: o.shape.name + ' · ' + (p.label || 'полка'),
          room: o.room,
          parent: o.id,
          part: i,
          x: o.x,
          z: o.z,
          y: o.y,
          shelf: p.action === 'shelf'
        }))
    )
  );
}
export function roomAt(x) {
  return x < -5 ? 2 : x > 5 ? 1 : 0;
}
