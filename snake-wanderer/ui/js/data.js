/** Как предметы меняют облик змейки. */
export function lookOf(R) {
  const has = (id) => !!R[id];
  const el = has('pyre') ? 'fire' : has('rime') ? 'ice' : has('venom') || has('plague') ? 'venom' : has('storm') ? 'storm' : null;
  return {
    el, spikes: has('thorns'), horns: has('horns'), halo: has('halo'), wings: has('wings'), crown: has('crown'), eye3: has('seeker'),
    fangs: has('fang') || has('basil'), twin: has('twin'), stripes: has('spine'), big: has('gullet'),
    tail: has('tailgun') ? 'sting' : has('pyre') ? 'flame' : has('rime') ? 'ice' : has('rapid') ? 'rattle' : null,
    tint: { fire: '#ff7a3d', ice: '#8fe3ff', venom: '#b06cff', storm: '#ffe45c' }[el] || (has('hydra') ? '#ff5a7a' : null),
    scale: 1 + (R.titan || 0) * 0.15,
    lunar: Object.keys(R).some((id) => id.indexOf('l_') === 0),
  };
}
