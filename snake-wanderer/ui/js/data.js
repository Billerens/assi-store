const clamp0 = (v, max) => Math.max(0, Math.min(max, Math.floor(Number(v) || 0)));

export function normSave(s) {
  const d = newSave();
  if (!s || typeof s !== 'object') return d;
  const out = Object.assign(d, s);
  out.stats = Object.assign(newSave().stats, s.stats || {});
  for (const k of ['perms', 'ach', 'cleared', 'hints', 'arts', 'artsOn', 'seen', 'bestiary', 'map']) if (!out[k] || typeof out[k] !== 'object') out[k] = {};
  if (!Array.isArray(out.skins) || !out.skins.length) out.skins = ['meadow'];
  if (!Array.isArray(out.waypoints)) out.waypoints = [];
  if (!DIFFS[out.diff]) out.diff = 1;
  out.shards = Math.max(0, Math.floor(Number(out.shards) || 0));
  out.moons = Math.max(0, Math.floor(Number(out.moons) || 0));
  if (!SPECIES.some((q) => q.id === out.species)) out.species = 'meadow';
  out.circle = clamp0(out.circle, MAX_CIRCLE); out.circleOn = clamp0(out.circleOn, out.circle);
  return out;
}

